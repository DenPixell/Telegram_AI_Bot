// Package pipeline - конвейер до LLM, который отсекает лишнее как можно раньше и дешевле:
//
//   - limits.go: rate limit на пользователя и суточные квоты LLM (пользователь, семья, всего);
//   - intents.go: служебные намерения без LLM («помощь», «панель», «мой часовой пояс ...»);
//   - filter.go: фильтр правил - стоп-слова и запрещённые темы, разбор суммы и даты,
//     простая трата целиком без LLM, неоднозначное - в агента;
//   - dictionary.go: словарь config/synonyms.yaml по основам слов (стеммер Портера);
//   - categorize.go, wiktionary.go: гибридная категория - словарь, кэш в БД, онлайн-тезаурус
//     (Викисловарь, только одно незнакомое слово), иначе решает LLM.
