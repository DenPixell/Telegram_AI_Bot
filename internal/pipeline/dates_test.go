package pipeline

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestFindDate(t *testing.T) {
	cases := []struct {
		in   string
		want string // "" - даты нет
	}{
		{"кофе 350", ""},
		{"кофе 350 сегодня", "2026-10-16"},
		{"такси 1200 вчера", "2026-10-15"},
		{"позавчера автобус 30", "2026-10-14"},
		{"в пятницу кино 900", "2026-10-16"}, // сегодня пятница
		{"в понедельник такси 800", "2026-10-12"},
		{"в субботу шашлык 2000", "2026-10-10"}, // ближайшая прошедшая
		{"кофе 350 12.10", "2026-10-12"},
		{"день рождения 6000 01.05.2025", "2025-05-01"},
		{"подарок 500 31.12.25", "2025-12-31"},
		{"кофе 350 5 марта", "2026-03-05"},
		{"такси 700 1 мая", "2026-05-01"},
		{"2 марта такси 500", "2026-03-02"},
		{"кофе 20.12", "2025-12-20"}, // без года и в будущем - прошлый год
		{"кофе 17.10", "2026-10-17"}, // завтра допустимо
		{"кофе 31.02", ""},           // несуществующая дата
		{"1.5к бензин", ""},          // «1.5» - сумма, а не 1 мая
	}
	for _, c := range cases {
		t.Run(c.in, func(t *testing.T) {
			d, ok := FindDate(c.in, today)
			if c.want == "" {
				assert.False(t, ok, "нашлась дата %s", d)
				return
			}
			if assert.True(t, ok) {
				assert.Equal(t, c.want, d.String())
			}
		})
	}
}
